//==============================================================================
//初期化処理
//==============================================================================
void Sky::Init()
{
	m_Layer = 1;
	m_Position = { 0.0f, 5.0f, 0.0f };
	m_Scale = { 100.0f, 100.0f, 100.0f };

	AddComponent<ModelRenderer>(this)->Load("asset\\model\\sky.obj");

}

//==============================================================================
//更新処理
//==============================================================================
void Sky::Update()
{
	CAMERA* camera = Manager::GetGameObject<CAMERA>();

	m_Position = camera->GetPosition();

	GameObject::Update();
}
